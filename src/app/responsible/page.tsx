"use client";
import Link from "next/link";
import { useEffect, useMemo, useState, type ReactNode } from "react";
import { useApp } from "@/components/AppProvider";
import { Button, Card, CustomerPicker, DataGate, Disclosure, DisclosureGroup, Icon, PageHeader, Pager, selectCls, Source, Stat, StatGroup, Tag, td, th } from "@/components/ui";
import { checkContactPolicy } from "@/lib/policy";
import { ACTION_SHORT, mainReason } from "@/lib/present";
import { baselineProbability } from "@/lib/trial";
import { csvSafe, fmtPct, fmtPp } from "@/lib/utils";

const SAFEGUARDS: [string, string][] = [
  ["Fictional demo data", "The demo uses made-up customers."],
  ["Consent first", "No consent or unsubscribed? They're never messaged."],
  ["Not too often", "Customers can't be messaged again too soon."],
  ["“No” means no", "If they say no, messages stop for 90 days. No discount pushing."],
  ["A person approves", "Nothing goes out until someone checks it."],
  ["Message checker", "Catches made-up offers, missing unsubscribe lines and pushy wording."],
  ["No sensitive data", "Age, gender, health and similar columns are deleted on upload."],
  ["Minimal personal data", "Names, emails and phone numbers are deleted. Messages say {first_name}."],
  ["Safe uploads", "Uploaded files are cleaned and checked before use."],
  ["Private keys", "The optional AI key stays on the server, never in the browser."],
  ["Honest numbers", "Estimates and simulated results are always labelled."],
];

const DISCLOSURE: [string, string, string][] = [
  ["Next.js 15 / React 19", "Application framework", "MIT"],
  ["Tailwind CSS 3", "Styling", "MIT"],
  ["Recharts 2", "Charts", "MIT"],
  ["Papa Parse 5", "CSV parsing in the browser", "MIT"],
  ["Vitest 3, puppeteer-core", "Automated tests (development only)", "MIT / Apache-2.0"],
  ["Anthropic Messages API", "Optional message drafting — only if a server key is configured", "Commercial API"],
  ["Synthetic dataset", "Generated by REGAIN (src/lib/sampleData.ts)", "Project-owned"],
];

const LIMITATIONS = [
  "Its estimates are educated guesses you can edit, not proven numbers.",
  "It can't see purchases made elsewhere.",
  "It only looks at the latest open complaint.",
  "Refunds aren't subtracted.",
  "Test results need real follow-up data — anything simulated is labelled.",
  "Data is saved in this browser only, for one user.",
];

function Check({ label, ok, children }: { label: string; ok: boolean | null; children: ReactNode }) {
  const icon = ok === null ? <span className="inline-block h-4 w-4" /> : ok ? <Icon name="check" className="h-4 w-4 text-good" /> : <Icon name="x" className="h-4 w-4 text-crimson-text" />;
  return (
    <div className="flex items-start gap-3 border-b border-line py-3 last:border-0">
      <span className="mt-0.5 shrink-0">{icon}</span>
      <div className="min-w-0 flex-1 text-sm">
        <div className="font-medium text-ink">{label}</div>
        <div className="mt-0.5 text-ink-soft">{children}</div>
      </div>
    </div>
  );
}

export default function ResponsiblePage() {
  return (
    <DataGate needsData={false}>
      <Inner />
    </DataGate>
  );
}

function Inner() {
  const { state, analysis } = useApp();
  const [aiOn, setAiOn] = useState<boolean | null>(null);
  const [filter, setFilter] = useState("all");
  const [page, setPage] = useState(0);
  const [cid, setCid] = useState<string | null>(
    state.selectedCustomerId && analysis.byId[state.selectedCustomerId]
      ? state.selectedCustomerId
      : (Object.values(analysis.trials).sort((x, y) => y.priorityScore - x.priorityScore)[0]?.customerId ?? null),
  );

  useEffect(() => {
    fetch("/api/generate-message").then((r) => r.json()).then((d: { aiAvailable: boolean }) => setAiOn(d.aiAvailable)).catch(() => setAiOn(false));
  }, []);
  useEffect(() => setPage(0), [filter]);

  const approvals = state.audit.filter((a) => a.type === "message_approved").length;
  const rejections = state.audit.filter((a) => a.type === "message_rejected").length;
  const sup = analysis.suppressed;
  const contactable = analysis.profiles.length - sup.opted_out - sup.no_consent;
  const a = state.assumptions;

  const entries = state.audit.filter((x) => filter === "all" || x.type === filter);
  const types = [...new Set(state.audit.map((x) => x.type))];
  const PAGE = 20;

  const check = useMemo(() => {
    if (!cid || !analysis.byId[cid]) return null;
    const p = analysis.byId[cid];
    const t = analysis.trials[cid];
    const pol = checkContactPolicy(p, state.interventions, state.asOf, a, state.suppressedUntil);
    const conv = state.conversations[cid];
    const expOutcomes = state.experiments.map((e) => e.outcomes[cid]).filter(Boolean);
    const imported = state.interventions.filter((r) => r.customerId === cid && r.source === "imported" && r.purchased !== "unknown");
    return { p, t, pol, conv, expOutcomes, imported };
  }, [cid, analysis, state, a]);

  const exportAudit = () => {
    const lines = ["id,timestamp,type,customer_id,detail", ...state.audit.map((x) => [x.id, x.at, x.type, x.customerId ?? "", x.detail].map(csvSafe).join(","))];
    const url = URL.createObjectURL(new Blob([lines.join("\n")], { type: "text/csv" }));
    const el = document.createElement("a");
    el.href = url;
    el.download = "regain-audit-log.csv";
    el.click();
    URL.revokeObjectURL(url);
  };

  return (
    <>
      <PageHeader title="Responsible AI & Audit" subtitle="Who you can contact, what was approved, and a log of everything." />

      <StatGroup cols={6}>
        <Stat label="Can be contacted" value={analysis.profiles.length ? contactable : "—"} hint="Gave consent, not unsubscribed" />
        <Stat label="Can't be contacted" value={sup.opted_out + sup.no_consent} hint={`${sup.opted_out} unsubscribed · ${sup.no_consent} no consent`} />
        <Stat label="Message limits" value={`${a.minDaysBetweenContacts}d · ${a.maxContactsPer90Days}/90d`} hint={`${sup.frequency_cap + sup.declined} paused for now`} tip={`At least ${a.minDaysBetweenContacts} days between messages, and no more than ${a.maxContactsPer90Days} in 90 days.`} />
        <Stat label="Messages checked" value={`${approvals} / ${rejections}`} hint="Approved / rejected" />
        <Stat label="Data" value={<span className="text-lg">{state.dataSource === "sample" ? "Demo" : state.dataSource === "upload" ? "Uploaded" : "None"}</span>} hint="Saved in this browser only" />
        <Stat label="AI writing" value={<span className="text-lg">{aiOn === null ? "…" : aiOn ? "On" : "Off"}</span>} hint={aiOn ? "Runs on the server" : "Messages use templates"} />
      </StatGroup>

      <div className="mt-6 grid gap-6 xl:grid-cols-[minmax(0,1fr)_minmax(0,1fr)]">
        <Card title="Check a customer" subtitle="Can we contact them, and why?" right={analysis.profiles.length > 0 && <CustomerPicker value={cid} onChange={setCid} />}>
          {!check ? (
            <p className="text-sm text-ink-muted">No customer data loaded.</p>
          ) : (
            <div>
              <Check label="Can we contact them?" ok={check.pol.allowed}>
                {check.pol.allowed ? "Yes — they gave consent and haven't been messaged too recently." : check.pol.reason}
                {check.pol.lastContactDate && <span className="block text-xs text-ink-muted">Last messaged {check.pol.lastContactDate} · {check.pol.contactsLast90} in the last 90 days</span>}
              </Check>
              <Check label="Was a message approved?" ok={check.conv ? check.conv.sends > 0 : null}>
                {check.conv ? (check.conv.sends > 0 ? `Yes — approved by a person (${check.conv.sends}). Sending is simulated in this demo.` : `Not yet — ${check.conv.status === "rejected" ? "it was rejected" : "waiting for someone to check it"}.`) : "No message written yet."}
              </Check>
              <Check label="Why this suggestion?" ok={null}>
                <span className="font-medium text-ink">{ACTION_SHORT[check.t.recommendedAction]}</span>. {mainReason(check.t)}{" "}
                <Link href={`/trial?id=${check.p.customerId}`} className="font-medium text-ink hover:underline">See details</Link>
              </Check>
              <Check label="Is the result real or simulated?" ok={null}>
                {check.expOutcomes.length
                  ? check.expOutcomes.map((o, i) => <span key={i} className="mr-2">{o.source === "simulated" ? <Source kind="simulated" /> : <Source kind="observed" />}</span>)
                  : check.imported.length
                    ? <><Source kind="observed" /> <span className="text-xs text-ink-muted">from imported records</span></>
                    : "No result yet."}
              </Check>
              <Check label="Numbers used" ok={null}>
                Chance they buy anyway {fmtPct(baselineProbability(check.p, a))}
                {check.t.recommendedAction !== "no_action" && ` · expected boost ${fmtPp(a.actions[check.t.recommendedAction].upliftPp)}`} · profit margin {fmtPct(a.marginRate)}.{" "}
                <Link href="/data#assumptions" className="font-medium text-ink hover:underline">Change</Link>
              </Check>
            </div>
          )}
        </Card>

        <DisclosureGroup className="self-start">
          <Disclosure flush title="How REGAIN keeps things safe" hint={`${SAFEGUARDS.length} rules`} defaultOpen>
            <ul className="space-y-2 text-sm">
              {SAFEGUARDS.map(([t, d]) => (
                <li key={t}><span><span className="font-medium text-ink">{t}.</span> <span className="text-ink-soft">{d}</span></span></li>
              ))}
            </ul>
          </Disclosure>
          <Disclosure flush title="What REGAIN is built with">
            <table className="w-full text-sm">
              <thead><tr className="border-b border-line"><th className={`${th} pl-0`}>Component</th><th className={th}>Use</th><th className={th}>Licence</th></tr></thead>
              <tbody>{DISCLOSURE.map(([x, y, z]) => <tr key={x} className="border-b border-line last:border-0"><td className="py-2 pr-3 font-medium">{x}</td><td className="px-4 py-2 text-ink-soft">{y}</td><td className="px-4 py-2 text-ink-soft">{z}</td></tr>)}</tbody>
            </table>
            <p className="mt-3 text-sm text-ink-muted">No real messages are ever sent.</p>
          </Disclosure>
          <Disclosure flush title="What REGAIN can't do yet">
            <ul className="list-disc space-y-1.5 pl-5 text-sm text-ink-soft">{LIMITATIONS.map((l) => <li key={l}>{l}</li>)}</ul>
          </Disclosure>
        </DisclosureGroup>
      </div>

      <Card
        title="Activity log"
        subtitle={`Everything done in REGAIN · ${state.audit.length} ${state.audit.length === 1 ? "event" : "events"}`}
        className="mt-6"
        padded={false}
        right={
          <div className="flex gap-2">
            <select className={selectCls} value={filter} onChange={(e) => setFilter(e.target.value)} aria-label="Filter audit events">
              <option value="all">All activity</option>
              {types.map((t) => <option key={t} value={t}>{t.replace(/_/g, " ")}</option>)}
            </select>
            <Button size="sm" icon="download" onClick={exportAudit} disabled={!state.audit.length}>Export</Button>
          </div>
        }
      >
        {entries.length === 0 ? (
          <p className="px-5 py-6 text-sm text-ink-muted">No events yet.</p>
        ) : (
          <>
            <div className="overflow-x-auto">
              <table className="w-full min-w-[680px] text-sm">
                <thead><tr className="border-b border-line"><th className={th}>Time</th><th className={th}>Event</th><th className={th}>Customer</th><th className={th}>Detail</th></tr></thead>
                <tbody>
                  {entries.slice(page * PAGE, page * PAGE + PAGE).map((x) => (
                    <tr key={x.id} className="border-b border-line align-top last:border-0">
                      <td className={`${td} whitespace-nowrap tabular-nums text-ink-soft`}>{x.at.replace("T", " ").slice(0, 16)}</td>
                      <td className={`${td} whitespace-nowrap`}><Tag>{x.type.replace(/_/g, " ")}</Tag></td>
                      <td className={`${td} text-ink-soft`}>{x.customerId ?? "—"}</td>
                      <td className={`${td} text-ink-soft`}>{x.detail}</td>
                    </tr>
                  ))}
                </tbody>
              </table>
            </div>
            <div className="border-t border-line"><Pager page={page} pages={Math.ceil(entries.length / PAGE)} onPage={setPage} total={entries.length} label="events" /></div>
          </>
        )}
      </Card>
    </>
  );
}
